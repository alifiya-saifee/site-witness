// Builds docs/rooms-and-agents.md from the same data the mockup uses, so the two never drift.
// Room data: docs/mockups/rooms-data.js. Room names, areas and presets: the ROOMS / ZONES / PRESETS
// lists in docs/mockups/diwan-onboarding-3d-mockup.html.
// Run: node scripts/build-rooms-doc.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { ROOM_DETAIL: R, STORY } = createRequire(import.meta.url)(join(root, 'docs/mockups/rooms-data.js'));
const html = readFileSync(join(root, 'docs/mockups/diwan-onboarding-3d-mockup.html'), 'utf8');

const rooms = [...html.matchAll(/^\s*\['(\w+)','([^']+)','(\w+)','([^']+)'\],?$/gm)].map(m => ({ key: m[1], name: m[2], zone: m[3], desc: m[4] }));
const zones = [...html.matchAll(/\{key:'(\w+)',name:'([^']+)',c:'#/g)].map(m => ({ key: m[1], name: m[2] }));
const core = html.match(/const CORE=\[([^\]]+)\]/)[1].match(/\w+/g);
const presets = Object.fromEntries([...html.matchAll(/^\s*(\w+):\[\.\.\.CORE,([^\]]+)\]/gm)].map(m => [m[1], [...core, ...m[2].match(/\w+/g)]]));
const TYPES = { brokerage: 'Real-estate brokerage', pm: 'Property manager / owners’ association', eng: 'Licensed engineering office', clinic: 'Clinic' };

const name = k => rooms.find(r => r.key === k).name;
const problems = [];
for (const r of rooms) if (!R[r.key]) problems.push(`no detail for ${r.key}`);
for (const k of Object.keys(R)) if (!rooms.find(r => r.key === k)) problems.push(`detail for unknown room ${k}`);
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

const out = [];
out.push('# Rooms and agents', '',
  '> Generated by `node scripts/build-rooms-doc.mjs` from `docs/mockups/rooms-data.js` and the room list in the sign-up',
  '> mockup. Edit those, then run the script. All names and figures are made up (sample data).', '',
  '**Status: designed, not built.** Everything below is shown in the mockup only; no agent runs yet.', '',
  '## Rules every room follows', '',
  '- Agents draft and prepare; **a named person decides**. Money, signatures, filings, public posts and devices that heat or move always need a person.',
  '- Every step is an event in one log. Facts get new versions; nothing is edited or deleted.',
  '- An approval is pinned to the facts it relied on. If one changes, the approval cancels itself and Compliance hears first.',
  '- Site Witness never says “pass”, “safe” or “compliant”. Only a signed human verdict can.', '',
  '## Rooms per office type', '',
  `Every office gets: ${core.map(name).join(', ')}.`, '',
  '| Office type | Adds | Rooms |', '|---|---|---|',
  ...Object.entries(presets).map(([t, ks]) => `| ${TYPES[t]} | ${ks.filter(k => !core.includes(k)).map(name).join(', ')} | ${ks.length} |`), '');

for (const z of zones) {
  out.push(`## ${z.name}`, '');
  for (const r of rooms.filter(r => r.zone === z.key)) {
    const d = R[r.key];
    out.push(`### ${r.name}`, '', `${r.desc}.`, '',
      `**Starts when:** ${d.starts.join(' · ')}`, '',
      '| Agent | Does | Tools | A person decides |', '|---|---|---|---|',
      ...d.agents.map(a => `| ${a.name} | ${a.does} | ${a.tools.join(', ')} | ${a.decides} |`), '',
      `**Hands to:** ${d.hands.map(name).join(', ')}`, '',
      `**Never:** ${d.never.join('; ')}.`, '');
  }
}

out.push('## Best case, end to end: “Follow a fix”', '',
  'Licensed engineering office, Al Noor Residence (sample). In the mockup: **▶ Follow a fix** in the office view, or open',
  '`diwan-onboarding-3d-mockup.html#eng/story=1`.', '',
  '| # | Room | Agent | What happens |', '|---|---|---|---|',
  ...STORY.map((s, i) => `| ${i + 1} | ${name(s.room)} | ${R[s.room].agents[s.agent].name} | **${s.title}.** ${s.text}${s.twist ? ' *(Mockup button: “What if the bank details change?” shows the payment cancelling itself.)*' : ''} |`), '');

writeFileSync(join(root, 'docs/rooms-and-agents.md'), out.join('\n'));
console.log(`docs/rooms-and-agents.md: ${rooms.length} rooms, ${rooms.reduce((n, r) => n + R[r.key].agents.length, 0)} agents, ${STORY.length} story steps`);
